// Символи, които стават емоджи.
//
// Замяната става при РИСУВАНЕ, не при запис. В базата остава точно каквото
// човек е написал — така търсенето в чата продължава да го намира, а ако
// някога решим, че това е глупост, се маха с един ред и нищо не е загубено.
//
// Заменя се само цял „къс" текст между интервали. „:)" става усмивка, но
// „http://нещо:)" не — там двоеточието принадлежи на адреса. По-добре една
// усмивка да не се хване, отколкото линк да се счупи.

const MAP = {
  ":)": "🙂", ":-)": "🙂", "=)": "🙂",
  ":(": "🙁", ":-(": "🙁", "=(": "🙁",
  ":D": "😀", ":-D": "😀", "xD": "😆", "XD": "😆",
  ";)": "😉", ";-)": "😉",
  ":P": "😛", ":-P": "😛", ":p": "😛",
  ":*": "😘", ":-*": "😘",
  ":o": "😮", ":O": "😮", ":-o": "😮", ":-O": "😮",
  ":|": "😐", ":-|": "😐",
  ":'(": "😢",
  "8)": "😎", "B)": "😎",
  "<3": "❤️", "</3": "💔",
  ":+1:": "👍", ":thumbsup:": "👍",
};

// Пунктуацията след усмивката е част от изречението, не от нея: „супер :)."
const TRAIL = /[.,!?…]+$/;

export function applyEmoticons(value) {
  const source = String(value || "");
  if (!source) return source;

  return source
    .split(/(\s+)/)
    .map((chunk) => {
      if (!chunk.trim()) return chunk;
      const tail = (chunk.match(TRAIL) || [""])[0];
      const core = tail ? chunk.slice(0, -tail.length) : chunk;
      const hit = MAP[core];
      return hit ? hit + tail : chunk;
    })
    .join("");
}
