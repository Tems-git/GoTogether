// Кръгчето до съобщение и в списъка с участници.
//
// Досега вътре стоеше буква върху цвят, изчислен от идентификатора — еднакво
// стабилно и еднакво безлично за всички. Сега, ако човек си е сложил снимка,
// на същото място стои тя.
//
// Компонентът нарочно не знае нито колко е голямо кръгчето, нито какъв е
// цветът, нито как се смятат буквите: всичко това се подава отвън, точно
// каквото беше и преди. Тоест на мястото на стария `View` се слага `Avatar`,
// старото съдържание влиза вътре като резерва и нищо друго не се пипа. Ако
// снимката липсва, се вижда буквално предишният вид.

import { useState } from "react";
import { View, Image } from "react-native";

export default function Avatar({ uri, style, children }) {
  // Връзката към снимката е временна и след час изтича; понякога файлът вече
  // го няма. И в двата случая се връщаме към буквата, вместо да оставим празен
  // кръг на екрана.
  //
  // Помни се ЗА КОЙ адрес се е провалило. Иначе един провал заключваше кръгчето
  // върху буквата завинаги — включително след смяна на снимката, когато адресът
  // вече е друг и няма причина да не се покаже.
  const [failedUri, setFailedUri] = useState(null);
  const failed = !!uri && failedUri === uri;

  if (uri && !failed) {
    return (
      <Image
        source={{ uri }}
        style={style}
        resizeMode="cover"
        onError={() => setFailedUri(uri)}
      />
    );
  }

  return <View style={style}>{children}</View>;
}
